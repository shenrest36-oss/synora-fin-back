CREATE TABLE `journal_entries` (
  `id` CHAR(36) NOT NULL,
  `companyId` CHAR(36) NOT NULL,
  `branchId` CHAR(36) NULL,
  `journalNumber` VARCHAR(50) NOT NULL,
  `referenceNumber` VARCHAR(80) NULL,
  `journalDate` DATE NOT NULL,
  `financialYearId` CHAR(36) NULL,
  `accountingPeriodId` CHAR(36) NULL,
  `description` TEXT NULL,
  `status` VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  `totalDebit` DECIMAL(18,2) NOT NULL DEFAULT 0.00,
  `totalCredit` DECIMAL(18,2) NOT NULL DEFAULT 0.00,
  `sourceType` VARCHAR(50) NULL,
  `sourceReferenceId` VARCHAR(100) NULL,
  `createdBy` CHAR(36) NULL,
  `submittedBy` CHAR(36) NULL,
  `approvedBy` CHAR(36) NULL,
  `postedBy` CHAR(36) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  `submittedAt` DATETIME(3) NULL,
  `approvedAt` DATETIME(3) NULL,
  `postedAt` DATETIME(3) NULL,
  `reversalOfJournalId` CHAR(36) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `journal_entries_companyId_journalNumber_key` (`companyId`, `journalNumber`),
  INDEX `journal_entries_companyId_idx` (`companyId`),
  INDEX `journal_entries_journalDate_idx` (`journalDate`),
  INDEX `journal_entries_status_idx` (`status`),
  INDEX `journal_entries_referenceNumber_idx` (`referenceNumber`),
  CONSTRAINT `journal_entries_companyId_fkey` FOREIGN KEY (`companyId`) REFERENCES `companies` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `journal_entries_branchId_fkey` FOREIGN KEY (`branchId`) REFERENCES `branches` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `journal_entries_financialYearId_fkey` FOREIGN KEY (`financialYearId`) REFERENCES `financial_years` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `journal_entries_accountingPeriodId_fkey` FOREIGN KEY (`accountingPeriodId`) REFERENCES `accounting_periods` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `journal_entries_reversalOfJournalId_fkey` FOREIGN KEY (`reversalOfJournalId`) REFERENCES `journal_entries` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE utf8mb4_unicode_ci;

